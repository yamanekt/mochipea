<?php

return [
    /*
     |--------------------------------------------------------------------------
     | アカウント削除の受け付け
     |--------------------------------------------------------------------------
     |
     | デモでアカウントを配布している間、参加者が誤って（あるいは面白半分で）
     | アカウントを消してしまわないよう、削除を一時的に止めるための設定。
     |
     |   false … 削除できない（デモ中。画面は出るが停止中の案内を表示）
     |   true  … 削除できる（通常運用）
     |
     | デモが終わったら .env の次の1行を消すか true にするだけで元に戻る。
     |
     |   ACCOUNT_DELETION_ENABLED=false
     |
     | 画面（account/delete.blade.php）は消していないので、
     | 切り替えるとそのまま削除フォームが復活する。
     |
     */
    'account_deletion_enabled' => env('ACCOUNT_DELETION_ENABLED', true),

    /*
     | 停止中に画面へ出す理由。文言だけ変えたいときはここを直す。
     */
    'account_deletion_notice' => env(
        'ACCOUNT_DELETION_NOTICE',
        'ただいまデモ期間中のため、アカウントの削除を一時的に停止しています。'
    ),
];
